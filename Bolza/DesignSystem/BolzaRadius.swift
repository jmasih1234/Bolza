import Foundation

/// Bolza corner radius tokens.
enum BolzaRadius {
    /// 8pt — small elements, chips.
    static let small: CGFloat = 8
    /// 10pt — controls, inputs.
    static let control: CGFloat = 10
    /// 12pt — standard cards.
    static let card: CGFloat = 12
    /// 14pt — prominent cards.
    static let cardLarge: CGFloat = 14
    /// 16pt — large imagery, hero cards.
    static let hero: CGFloat = 16
}
